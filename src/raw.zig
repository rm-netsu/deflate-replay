//! Raw (inflated) data sink: 32 KiB history ring, optional output copy,
//! optional expected-data verification, Adler-32 / CRC-32 accumulation.

const std = @import("std");

pub const ring_size: usize = 1 << 16;
pub const ring_mask: u64 = ring_size - 1;

pub const Error = std.Io.Writer.Error || error{RawMismatch};

pub const RawSink = struct {
    ring: [ring_size]u8 = undefined,
    head: u64 = 0,
    out: ?*std.Io.Writer = null,
    expect: ?[]const u8 = null,
    expect_pos: usize = 0,
    mismatch_at: ?u64 = null,
    adler: u32 = 1,
    crc: std.hash.Crc32 = undefined,

    pub fn start(self: *RawSink, out: ?*std.Io.Writer, expect: ?[]const u8) void {
        self.head = 0;
        self.out = out;
        self.expect = expect;
        self.expect_pos = 0;
        self.mismatch_at = null;
        self.adler = 1;
        self.crc = std.hash.Crc32.init();
    }

    fn emit(self: *RawSink, b: u8) Error!void {
        self.ring[@intCast(self.head & ring_mask)] = b;
        self.head += 1;
        self.adler = std.hash.Adler32.permute(self.adler, &[1]u8{b});
        self.crc.update(&[1]u8{b});
        if (self.out) |w| try w.writeByte(b);
        if (self.expect) |exp| {
            if (self.expect_pos >= exp.len or exp[self.expect_pos] != b) {
                self.mismatch_at = self.expect_pos;
                return error.RawMismatch;
            }
            self.expect_pos += 1;
        }
    }

    pub fn put(self: *RawSink, b: u8) Error!void {
        try self.emit(b);
    }

    pub fn putSlice(self: *RawSink, bytes: []const u8) Error!void {
        for (bytes) |b| try self.emit(b);
    }

    /// Overlap-safe LZ77 copy; `dist` may exceed `head` only for FDICT streams
    /// (garbage ring reads are harmless there: the compressed output never
    /// depends on regenerated bytes).
    pub fn copyMatch(self: *RawSink, dist: u32, len: u32) Error!void {
        var i: u32 = 0;
        while (i < len) : (i += 1) {
            const src = self.head -% dist;
            try self.emit(self.ring[@intCast(src & ring_mask)]);
        }
    }

    pub fn crcFinal(self: *const RawSink) u32 {
        return self.crc.final();
    }
};

test "sink match copy with overlap" {
    var sink: RawSink = undefined;
    sink.start(null, null);
    try sink.putSlice("abc");
    try sink.copyMatch(3, 7); // "abcabca"
    try std.testing.expectEqual(@as(u64, 10), sink.head);
    var check: RawSink = undefined;
    check.start(null, "abcabcabca");
    try check.putSlice("abc");
    try check.copyMatch(3, 7);
    try std.testing.expectEqual(@as(usize, 10), check.expect_pos);
    try std.testing.expect(check.mismatch_at == null);
}

test "sink mismatch detection" {
    var sink: RawSink = undefined;
    sink.start(null, "xyz");
    try sink.putSlice("xy");
    try std.testing.expectError(error.RawMismatch, sink.put('y'));
    try std.testing.expectEqual(@as(u64, 2), sink.mismatch_at.?);
}

test "checksum known vectors" {
    var sink: RawSink = undefined;
    sink.start(null, "Wikipedia");
    try sink.putSlice("Wikipedia");
    try std.testing.expectEqual(@as(u32, 0x11E60398), sink.adler);
    try std.testing.expectEqual(@as(u32, 0xCBF43926), std.hash.Crc32.hash("123456789"));
}
